test('排名公开核验与三种报告 PNG 导出', async ({ page }) => {
  await page.goto('/compare')
  await page.getByRole('button', { name: '平台排名', exact: true }).click()
  await page.getByRole('button', { name: '公开计算核验', exact: true }).click()
  const d = page.getByRole('dialog')
  for (let i = 0; i < 6; i++) await d.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(d).toContainText('与当前排名结果一致')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '导出报告', exact: true }).click()
  for (const [template, layout, w, h] of [
    ['排行榜', '竖版 9:16', 1080, 1920],
    ['单平台', '横版 16:9', 1920, 1080],
    ['平台对比', '横版 16:9', 1920, 1080],
  ] as const) {
    await d.getByRole('button', { name: template, exact: true }).click()
    await d.getByRole('button', { name: layout, exact: true }).click()
    await expect(d.getByRole('img', { name: '体育赔率报告预览' })).toBeVisible()
    await page.waitForTimeout(80)
    const downloading = page.waitForEvent('download')
    await d.getByRole('button', { name: '下载 PNG' }).click()
    const download = await downloading
    const data = await readFile((await download.path())!)
    expect(data.subarray(1, 4).toString()).toBe('PNG')
    expect(data.readUInt32BE(16)).toBe(w)
    expect(data.readUInt32BE(20)).toBe(h)
    await download.saveAs(`outputs/sports-planning/${download.suggestedFilename()}`)
  }
})
