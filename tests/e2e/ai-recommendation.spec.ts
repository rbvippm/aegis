import { test, expect } from '@playwright/test'
test('推荐候选、来源与限定追问沿用同一范围', async ({ page }) => {
  await page.goto('/ai')
  while (!(await page.getByRole('button', { name: '按盾牌分推荐值得优先了解的平台', exact: true }).count()))
    await page.getByRole('button', { name: '换一批推荐问题', exact: true }).click()
  await page.getByRole('button', { name: '按盾牌分推荐值得优先了解的平台', exact: true }).click()
  const candidates = page.getByRole('region', { name: '推荐候选' })
  await expect(candidates.locator('h3')).toHaveText(['平台 A', '平台 J · 国际站', '平台 F'])
  await expect(candidates).toContainText('优先了解')
  await page.getByRole('button', { name: '改按资金活跃度推荐', exact: true }).click()
  await expect(page.locator('.ac-project-intro').last()).toContainText('同窗口存款额')
  await page.getByRole('button', { name: '查看候选平台近30天资金表现', exact: true }).last().click()
  await expect(page.locator('.ac-project-intro').last()).toContainText('30d')
  const table = page.getByRole('region', { name: '同窗口资金指标' })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: '来源与更新时间', exact: true }).last().click()
  await expect(page.getByRole('dialog')).toContainText('固定资金快照')
})
test('平台 F 入口使用当前平台与链币种，回到详情保留同范围', async ({ page }) => {
  await page.goto('/monitor?platform=F&period=7d&chains=TRON&tokens=USDT')
  const detail = page.getByRole('dialog', { name: '平台 F · 详情', exact: true })
  await expect(detail).toBeVisible()
  await expect(
    detail.getByRole('link', { name: '让 AI 解读平台数据', exact: true }),
  ).toHaveAttribute('href', /7d/)
  await detail.getByRole('link', { name: '让 AI 解读平台数据', exact: true }).click()
  const intro = page.locator('.ac-project-intro')
  await expect(intro).toContainText('平台 F')
  await expect(intro).toContainText('7d')
  await expect(intro).toContainText('TRON')
  await expect(intro).not.toContainText('平台 B')
  const link = page.getByRole('link', { name: '查看平台 F完整详情', exact: true })
  await expect(link).toHaveAttribute('href', /period=7d/)
  await expect(link).toHaveAttribute('href', /tokens=USDT/)
})
test('体育入口严格保留市场和选项，追问不回落到旧赛事报价', async ({ page }) => {
  await page.goto(
    '/ai?source=sports&analyze=1&fixture=north-south&market=total&selection=1&category=all&revision=1&q=' +
      encodeURIComponent('北辰队对南岳队，总分小分报价如何核验？'),
  )
  const intro = page.locator('.ac-project-intro')
  await expect(intro).toContainText('总分')
  await expect(intro).toContainText('版本 1')
  await expect(intro).toContainText('小')
  await page.getByRole('button', { name: '这个盘口有哪些核对项？', exact: true }).click()
  await expect(page.locator('.ac-project-intro').last()).toContainText('选项 2/2')
  await expect(page.locator('.ac-project-intro').last()).toContainText('版本 1')
  const returnLink = page.getByRole('link', { name: '返回同场同市场核对', exact: true }).last()
  await expect(returnLink).toHaveAttribute('href', /revision=1/)
  await expect(returnLink).toHaveAttribute('href', /selection=1/)
  await returnLink.click()
  await expect(page).toHaveURL(/revision=1/)
  await expect(page.getByRole('dialog')).toContainText('总分 224.5')
  const again = page
    .getByRole('dialog')
    .getByRole('link', { name: '让 AI 解读当前数据', exact: true })
  await expect(again).toHaveAttribute('href', /fixture=north-south/)
  await expect(again).toHaveAttribute('href', /selection=1/)
  await again.click()
  await expect(page.locator('.ac-project-intro')).toContainText('北辰队')
  await expect(page.locator('.ac-project-intro')).toContainText('版本 1')
  await expect(page.getByText('报价范围无法还原', { exact: true })).toHaveCount(0)
})
