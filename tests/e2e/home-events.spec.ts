import { test, expect } from '@playwright/test'
import { chooseOption } from './helpers/select'

test('热门赛事支持逐场、逐玩法推荐与报价/盘口详情', async ({ page }) => {
  await page.goto('/')
  const card = page.getByRole('region', { name: '赛事与机会', exact: true })
  await expect(card).toContainText('足球 · 亚洲联赛')
  await expect(card).toContainText('下半场 63:24')
  await expect(card.locator('.he-quote')).toHaveCount(2)
  await card.getByRole('button', { name: '平台 B · 主 -0.5 · 报价详情', exact: true }).click()
  const drawer = page.getByRole('dialog')
  await expect(page).toHaveURL(/\/$/)
  await expect(drawer).toContainText('同盘口报价详情')
  await expect(drawer.locator('.he-quote-row--down')).toContainText('0.94 → 0.90')
  await expect(drawer).toContainText('暂停报价')
  await expect(drawer).toContainText('报价过期')
  await page.keyboard.press('Escape')
  await chooseOption(page, card.getByRole('combobox', { name: '推荐玩法', exact: true }), 'total')
  await expect(card.locator('.he-selection').first()).toHaveText('大 2.5')
  await card.getByRole('button', { name: /同场 · 同盘 · 同选项/ }).click()
  await expect(drawer).toContainText('总分/进球数高于盘口为大')
  await page.keyboard.press('Escape')
  await card.getByRole('button', { name: '下一场热门赛事' }).click()
  await expect(card).toContainText('篮球 · 篮球联赛')
  await expect(card).toContainText('北辰队')
  await expect(card.locator('.he-selection').first()).toHaveText('大 224.5')
  await card.getByRole('button', { name: '上一场热门赛事' }).click()
  await expect(card).toContainText('海港队')
})

test('套利逐条展示，首页打开分配试算，收益不冒充已核验净收益', async ({ page }) => {
  await page.goto('/')
  const card = page.getByRole('region', { name: '赛事与机会', exact: true })
  await card.getByRole('button', { name: '套利机会', exact: true }).click()
  await expect(card).toContainText('篮球 · 篮球联赛')
  await expect(card).toContainText('胜负 · 两项结果')
  await expect(card.locator('.he-profit')).toContainText('+50.00')
  await expect(card).toContainText('净收益待核算')
  await card.getByRole('button', { name: '下一个套利机会' }).click()
  await expect(card).toContainText('东岚队')
  await card.getByRole('button', { name: '上一个套利机会' }).click()
  await expect(card).toContainText('北辰队')
  await card.getByRole('button', { name: '查看分配试算', exact: true }).click()
  const drawer = page.getByRole('dialog')
  await expect(page).toHaveURL(/\/$/)
  await expect(drawer).toContainText('分配试算')
  await expect(drawer).toContainText('北辰队')
  await drawer.getByRole('spinbutton', { name: '总预算' }).fill('2000')
  await expect(drawer.locator('.sp-gross')).toContainText('+100.00 USDT')
  await expect(drawer.locator('.sp-net-result')).toContainText('理论净收益待核算')
  await drawer.getByRole('spinbutton', { name: '预计总成本' }).fill('20')
  await expect(drawer.locator('.sp-net-result')).toContainText('+80.00 USDT')
  await drawer.getByRole('spinbutton', { name: '预计总成本' }).fill('150')
  await expect(drawer.locator('.sp-net-result')).toContainText('-50.00 USDT')
  await drawer.getByRole('spinbutton', { name: '预计总成本' }).fill('')
  await expect(drawer.locator('.sp-net-result')).toContainText('待核算')
})

test('动态格式同步、涨跌图标、盘口和暂停详情、最近20条', async ({ page }) => {
  await page.goto('/')
  const card = page.getByRole('region', { name: '赛事与机会', exact: true })
  await card.getByRole('button', { name: '滚球动态', exact: true }).click()
  await expect(card.locator('.he-movement')).toHaveCount(3)
  await expect(card.locator('.he-movement--down')).toContainText('0.94 → 0.90')
  await expect(card.locator('.he-movement--line')).toContainText('主队 -2.5 → 主队 -3.5')
  await card.getByRole('button', { name: /暂停报价：/ }).click()
  const drawer = page.getByRole('dialog')
  await expect(drawer).toContainText('恢复前不生成有效赔率')
  await page.keyboard.press('Escape')
  await card.getByRole('button', { name: '港盘 HK', exact: true }).click()
  await drawer.getByRole('button', { name: '十进制 DEC', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(card.locator('.he-movement--down')).toContainText('1.94 → 1.90')
  await expect(card).not.toContainText('原记录')
  await card.getByRole('button', { name: '查看全部', exact: true }).click()
  await expect(drawer.locator('.he-movement')).toHaveCount(20)
  await expect(drawer.locator('.he-movement--up').first()).toContainText('1.90 → 1.92')
  await drawer
    .getByRole('button', { name: '盘口变化：平台 A 主队 -2.5 → 主队 -3.5', exact: true })
    .click()
  await expect(drawer).toContainText('新旧盘口需分别比较')
  await expect(drawer).toContainText('主队 -2.5 → 主队 -3.5')
})

for (const width of [360, 390, 430]) {
  test(`${width}px 三个推荐页与本地弹框无横向溢出`, async ({ page }) => {
    await page.setViewportSize({ width, height: 932 })
    await page.goto('/')
    const card = page.getByRole('region', { name: '赛事与机会', exact: true })
    for (const tab of ['热门赛事', '套利机会', '滚球动态']) {
      await card.getByRole('button', { name: tab, exact: true }).click()
      await card.scrollIntoViewIfNeeded()
      expect(await card.evaluate((el) => el.scrollWidth > el.clientWidth + 1)).toBe(false)
      expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(
        false,
      )
      if (process.env.AEGIS_CAPTURE_UI === '1')
        await page.screenshot({ path: `outputs/home-events/${width}-${tab}.png` })
    }
    await card.getByRole('button', { name: '查看全部', exact: true }).click()
    await expect(page.getByRole('dialog').locator('.he-movement')).toHaveCount(20)
    expect(
      await page.getByRole('dialog').evaluate((el) => el.scrollWidth > el.clientWidth + 1),
    ).toBe(false)
    if (process.env.AEGIS_CAPTURE_UI === '1')
      await page.screenshot({ path: `outputs/home-events/${width}-history.png` })
  })
}
