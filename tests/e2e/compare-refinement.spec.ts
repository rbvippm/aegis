import { test, expect } from '@playwright/test'
import { chooseOption } from './helpers/select'
const firstMatch = (page: import('@playwright/test').Page) =>
  page.getByRole('article', { name: '北辰队对南岳队', exact: true })
test('紧凑头部、分组子玩法与三秒涨跌反馈', async ({ page }) => {
  await page.goto('/compare')
  await expect(page.locator('.sp-intro')).toHaveCount(0)
  await expect(page.locator('.sp-match')).toHaveCount(6)
  const card = firstMatch(page)
  await expect(card.locator('.pw-periods button')).toHaveCount(3)
  await card.locator('.pw-periods button').nth(1).click()
  await expect(card.getByRole('button', { name: /^平台 A 主 -1.5 / })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await card.getByRole('button', { name: '大小分', exact: true }).click()
  await expect(card.locator('.pw-periods')).toContainText('上半场')
  await expect(card.locator('.sp-change-up')).not.toHaveCount(0)
  await expect(card.locator('.sp-change-down')).not.toHaveCount(0)
  const arrow = card.locator('.sp-price-arrow').first()
  expect(await arrow.evaluate((el) => getComputedStyle(el).animationIterationCount)).toBe('3')
  await expect
    .poll(
      () =>
        arrow.evaluate((el) => el.getAnimations().filter((a) => a.playState === 'running').length),
      { timeout: 5000 },
    )
    .toBe(0)
  await page.getByRole('button', { name: '玩法与赔率设置 · 港盘 HK', exact: true }).click()
  const drawer = page.getByRole('dialog')
  await drawer.getByRole('button', { name: /欧盘 DEC/ }).click()
  await drawer.getByRole('checkbox', { name: '胜负', exact: true }).uncheck()
  await drawer.getByRole('button', { name: '完成设置' }).click()
  await expect(card.getByRole('button', { name: '胜负', exact: true })).toHaveCount(0)
  await expect(
    page.getByRole('button', { name: '玩法与赔率设置 · 欧盘 DEC', exact: true }),
  ).toBeVisible()
})
