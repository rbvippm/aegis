test('具体提醒设置同步系统消息，刷新及编辑后保持一致', async ({ page }) => {
  await page.goto('/compare')
  await firstMatch(page).getByRole('button', { name: '提醒', exact: true }).click()
  let drawer = page.getByRole('dialog')
  await chooseOption(page, drawer.getByRole('combobox', { name: '提醒平台', exact: true }), 'B')
  await drawer.getByRole('textbox', { name: '目标赔率' }).fill('0.99')
  await drawer.getByRole('button', { name: '保存提醒设置' }).click()
  await expect(drawer).toContainText('详情已同步到消息中心')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /提醒设置 1 条/ }).click()
  await expect(drawer).toContainText('北辰队 vs 南岳队')
  await expect(drawer).toContainText('平台 B')
  await expect(drawer).toContainText('赔率 ≥ 0.99')
  await drawer.getByRole('link', { name: '前往消息中心' }).click()
  await page.getByRole('button', { name: '系统', exact: true }).click()
  const message = page.locator('.pf-notice').filter({ hasText: '北辰队 vs 南岳队 · 提醒设置' })
  await expect(message).toContainText('观察 30秒 · 冷却 5分钟')
  await page.reload()
  await page.getByRole('button', { name: '系统', exact: true }).click()
  await message.click()
  await expect(page).toHaveURL(/compare\?panel=reminders/)
  drawer = page.getByRole('dialog')
  await drawer.getByRole('button', { name: '编辑提醒' }).click()
  await expect(drawer.getByRole('textbox', { name: '目标赔率' })).toHaveValue('0.99')
  await expect(drawer.getByRole('combobox', { name: '提醒平台', exact: true })).toContainText(
    '平台 B',
  )
  await drawer.getByRole('textbox', { name: '目标赔率' }).fill('1.01')
  await drawer.getByRole('button', { name: '保存提醒设置' }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /提醒设置 1 条/ }).click()
  await drawer.getByRole('button', { name: '删除提醒', exact: true }).click()
  await expect(drawer).toContainText('暂无提醒')
})
